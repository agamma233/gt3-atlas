"""Build the static site using Python 3 standard library only.

The garage page is rendered from data/cars.json and src/cards/*.html.
The three showroom pages use the shared src/showroom.html template and are
generated by scripts/showroom_builder.py. `--offline` adds a self-contained
single-file garage; the showroom routes are intentionally not embedded.
"""
from pathlib import Path
import html
import json
import re
import shutil
import argparse
import base64

from showroom_builder import (
    FEATURED,
    SHOWROOM_HERO_LINK,
    SHOWROOM_NAV_LINK,
    build_showrooms,
    render_showroom_drawer,
    render_showroom_link,
    render_showroom_rail,
)

ROOT = Path(__file__).resolve().parents[1]
SITE = "https://agamma233.github.io/gt3-atlas"
LAST_MOD = "2026-10-21"


def render(showrooms=True):
    cars = json.loads((ROOT / "data/cars.json").read_text(encoding="utf-8"))
    assert len({c["id"] for c in cars}) == len(cars), "Duplicate car IDs"
    page = (ROOT / "src/page.html").read_text(encoding="utf-8")
    for car in cars:
        card = (ROOT / "src/cards" / (car["id"] + ".html")).read_text(encoding="utf-8")
        for key in ("title", "team"):
            if key in car:
                card = card.replace("{{" + key + "}}", html.escape(car[key]))
        for key, value in car["metadata"].items():
            if key == "data-title":
                value = car["title"]
            card = card.replace("{{meta:" + key + "}}", html.escape(str(value), quote=True))
        specs_by_label = {row["label"]: row["value_html"] for row in car["specs"]}
        for i, fallback in enumerate(car["hud"]):
            label = ("发动机", "功率", "动力布局")[i] if i < 3 else ""
            card = card.replace("{{hud:" + str(i) + "}}", specs_by_label.get(label, html.escape(fallback)))
        rows = "".join(
            '<div class="spec-row"><span class="idx" aria-hidden="true">'
            + str(i).zfill(2)
            + "</span><dt>"
            + html.escape(row["label"])
            + "</dt><dd>"
            + row["value_html"]
            + "</dd></div>"
            for i, row in enumerate(car["specs"], 1)
        )
        card = card.replace("{{specs}}", rows)
        card = card.replace("{{showroom-link}}", render_showroom_link(car["id"]) if showrooms else "")
        page = page.replace("{{card:" + car["id"] + "}}", card)
    feature_id = FEATURED[0]
    page = page.replace("{{showroom-nav-link}}", SHOWROOM_NAV_LINK if showrooms else "")
    page = page.replace("{{showroom-drawer}}", render_showroom_drawer() if showrooms else "")
    page = page.replace("{{showroom-feature-id}}", feature_id if showrooms else "")
    page = page.replace("{{showroom-feature-href}}", f"cars/{feature_id}/" if showrooms else f"#{feature_id}")
    page = page.replace("{{showroom-feature-cta}}", "进入数字展厅 / SHOWROOM" if showrooms else "打开完整车辆档案 / DOSSIER")
    page = page.replace("{{showroom-rail}}", render_showroom_rail() if showrooms else "")
    page = page.replace("{{showroom-hero-link}}", SHOWROOM_HERO_LINK if showrooms else "")
    assert not re.search(r"\{\{(?:card:|meta:|title|team|specs|showroom)", page), "Unresolved template token"
    return page


def write_sitemap(out):
    urls = [SITE + "/"] + [f"{SITE}/cars/{sid}/" for sid in FEATURED]
    body = "\n".join(
        f"  <url><loc>{html.escape(url)}</loc><lastmod>{LAST_MOD}</lastmod></url>"
        for url in urls
    )
    (out / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + body
        + "\n</urlset>\n",
        encoding="utf-8",
    )


def build(offline=False):
    page = render(showrooms=True)
    out = ROOT / "dist"
    out.mkdir(exist_ok=True)
    shutil.copytree(ROOT / "assets", out / "assets", dirs_exist_ok=True)
    for name in (".nojekyll", "robots.txt", "sitemap.xml", "NOTICE.md", "LICENSE"):
        shutil.copy2(ROOT / name, out / name)
    (out / "index.html").write_text(page, encoding="utf-8")
    (ROOT / "index.html").write_text(page, encoding="utf-8")
    pages = build_showrooms()
    write_sitemap(out)

    if offline:
        offline_page = render(showrooms=False)
        offline_page = offline_page.replace(
            '<link rel="stylesheet" href="assets/style.css">',
            "<style>" + (ROOT / "assets/style.css").read_text(encoding="utf-8") + "</style>",
        )
        offline_page = offline_page.replace(
            '<script src="assets/app.js"></script>',
            "<script>" + (ROOT / "assets/app.js").read_text(encoding="utf-8") + "</script>",
        )

        def embed(match):
            path = ROOT / match[0]
            mime = "image/jpeg" if path.suffix == ".jpg" else "image/" + path.suffix[1:]
            return "data:" + mime + ";base64," + base64.b64encode(path.read_bytes()).decode("ascii")

        offline_page = re.sub(r"assets/images/[a-f0-9]+\.(?:jpg|png|webp)", embed, offline_page)
        offline_path = out / "gt3-atlas-offline.html"
        offline_path.write_text(offline_page, encoding="utf-8")
        print("Built dist/gt3-atlas-offline.html (" + str(offline_path.stat().st_size) + " bytes)")

    print("Built dist/index.html (" + str((out / "index.html").stat().st_size) + " bytes)")
    print("Built " + str(len(pages)) + " showroom routes: " + ", ".join(page["id"] for page in pages))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--offline", action="store_true", help="Also generate a single-file offline copy")
    build(parser.parse_args().offline)
